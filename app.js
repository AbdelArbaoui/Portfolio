const languageButtons = document.querySelectorAll("[data-language-toggle]");
const demoDialog = document.getElementById("demo-dialog");
const demoFrame = document.getElementById("demo-frame");
const demoTitle = document.getElementById("demo-title");
const demoLoader = document.querySelector("[data-demo-loader]");
const closeDemoButton = document.querySelector("[data-close-project]");
const demoExternalButton = document.querySelector("[data-demo-external]");

let currentLanguage = getInitialLanguage();
let currentProject = null;

function getInitialLanguage() {
  const queryLanguage = new URLSearchParams(window.location.search).get("lang");
  if (queryLanguage === "fr" || queryLanguage === "en") return queryLanguage;

  try {
    return localStorage.getItem("portfolioLanguage") === "en" ? "en" : "fr";
  } catch {
    return "fr";
  }
}

function translate(key) {
  return translations[currentLanguage][key] || key;
}

function setLanguage(language) {
  currentLanguage = language === "en" ? "en" : "fr";
  document.documentElement.lang = currentLanguage;
  document.title = translations[currentLanguage].pageTitle;
  document.querySelector('meta[name="description"]').content = translations[currentLanguage].pageDescription;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    element.textContent = translate(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach(element => {
    element.setAttribute("aria-label", translate(element.dataset.i18nAria));
  });

  document.querySelectorAll("[data-i18n-alt]").forEach(element => {
    element.setAttribute("alt", translate(element.dataset.i18nAlt));
  });

  document.querySelectorAll("[data-i18n-title]").forEach(element => {
    element.setAttribute("title", translate(element.dataset.i18nTitle));
  });

  const nextLanguage = currentLanguage === "fr" ? "EN" : "FR";
  const languageLabel = currentLanguage === "fr"
    ? "Afficher le site en anglais"
    : "Show the website in French";

  languageButtons.forEach(button => {
    button.textContent = nextLanguage;
    button.setAttribute("aria-label", languageLabel);
  });

  try {
    localStorage.setItem("portfolioLanguage", currentLanguage);
  } catch {
    // The portfolio remains usable when storage is unavailable.
  }

  if (currentProject && demoFrame.contentWindow) {
    demoFrame.contentWindow.postMessage({
      type: "portfolio-language",
      language: currentLanguage
    }, "*");
  }
}

function toggleLanguage() {
  setLanguage(currentLanguage === "fr" ? "en" : "fr");
}

function getProjectUrl(projectKey) {
  const url = new URL(projects[projectKey].path, window.location.href);
  url.searchParams.set("lang", currentLanguage);
  return url;
}

function openProject(projectKey) {
  if (!projects[projectKey]) return;

  currentProject = projectKey;
  demoTitle.textContent = projects[projectKey].title;
  demoLoader.classList.remove("is-hidden");
  demoFrame.src = getProjectUrl(projectKey).href;
  demoDialog.showModal();
  closeDemoButton.focus();
}

function closeProject() {
  if (!demoDialog.open) return;
  demoDialog.close();
}

function resetDemo() {
  demoFrame.src = "about:blank";
  demoLoader.classList.remove("is-hidden");
  currentProject = null;
}

function openProjectExternally(projectKey = currentProject) {
  if (!projectKey || !projects[projectKey]) return;
  window.open(getProjectUrl(projectKey).href, "_blank", "noopener,noreferrer");
}

languageButtons.forEach(button => {
  button.addEventListener("click", toggleLanguage);
});

document.querySelectorAll("[data-open-project]").forEach(button => {
  button.addEventListener("click", () => openProject(button.dataset.openProject));
});

document.querySelectorAll("[data-open-external]").forEach(button => {
  button.addEventListener("click", () => openProjectExternally(button.dataset.openExternal));
});

closeDemoButton.addEventListener("click", closeProject);
demoExternalButton.addEventListener("click", () => openProjectExternally());
demoDialog.addEventListener("close", resetDemo);

demoDialog.addEventListener("click", event => {
  if (event.target === demoDialog) closeProject();
});

demoFrame.addEventListener("load", () => {
  if (!currentProject) return;
  demoLoader.classList.add("is-hidden");
  demoFrame.contentWindow?.postMessage({
    type: "portfolio-language",
    language: currentLanguage
  }, "*");
});

window.addEventListener("message", event => {
  if (
    event.source === demoFrame.contentWindow &&
    event.data?.type === "portfolio-language" &&
    ["fr", "en"].includes(event.data.language) &&
    event.data.language !== currentLanguage
  ) {
    setLanguage(event.data.language);
  }
});

window.addEventListener("storage", event => {
  if (
    event.key === "portfolioLanguage" &&
    ["fr", "en"].includes(event.newValue) &&
    event.newValue !== currentLanguage
  ) {
    setLanguage(event.newValue);
  }
});

